defmodule OaksWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :oaks

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  # The session cookie holds the login session token, so it is encrypted as
  # well as signed, never readable by page scripts (http_only), and in
  # production only sent over HTTPS (secure).
  @session_options [
    store: :cookie,
    key: "_oaks_key",
    signing_salt: "VkRbKLCN",
    encryption_salt: "q6m0Zr1Hxv",
    same_site: "Lax",
    http_only: true,
    secure: Application.compile_env(:oaks, :secure_cookies, false)
  ]

  socket "/live", Phoenix.LiveView.Socket,
    # peer_data, user_agent, and x_headers feed the analytics visitor hash
    # (OaksWeb.Analytics.TrackPageView); behind Fly the client IP arrives in
    # X-Forwarded-For, which x_headers includes.
    websocket: [connect_info: [:peer_data, :user_agent, :x_headers, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :user_agent, :x_headers, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  #
  # `only_matching` is used for root-level files (favicon, robots,
  # site.webmanifest) so that their digested variants (e.g.
  # `/favicon-<hash>.ico`) are served too — `only` requires exact
  # first-segment matches and would let digested URLs fall through to
  # the router as 404s.
  plug Plug.Static,
    at: "/",
    from: :oaks,
    gzip: not code_reloading?,
    only: ~w(assets fonts images),
    only_matching: ~w(favicon robots site),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :oaks
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # OaksWeb.BodyDigest hashes the raw body of import requests, which the
  # import's dry-run token is bound to; other requests read as usual.
  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    body_reader: {OaksWeb.BodyDigest, :read_body, []},
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  # Analytics tracking lives at the endpoint level so it sees every request,
  # including unrouted paths that 404 — those never enter a router pipeline.
  plug OaksWeb.Plugs.Analytics
  plug OaksWeb.Plugs.ApiHost
  plug OaksWeb.Router
end
